import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const data = path.join(root, "src/data/identified-shocks");
const macro = path.join(root, "src/data/macro-drivers");
const read = (name, dir = data) => JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"));
const failures = []; let tests = 0;
const check = (ok, message) => { tests += 1; if (!ok) failures.push(message); };
const manifest = read("jk_author_reference_manifest.json");
const exclusions = read("jk_author_event_exclusion_registry.json");
const pc1 = read("jk_pc1_replication_validation.json");
const poor = read("jk_poor_man_replication_validation.json");
const median = read("jk_median_rotation_replication_validation.json");
const monthly = read("jk_monthly_replication_validation.json");
const comparison = read("jk_author_reference_comparison.json");
const cross = read("jk_cross_language_validation.json");
const event = read("jk_event_level_shocks.json");
const mp = read("ecb_pure_monetary_policy_shock_monthly.json");
const cbi = read("ecb_central_bank_information_shock_monthly.json");
const info = read("monetary_policy_information_effect_registry.json");
const shocks = read("shock_identification_registry.json", macro);
const lp = read("lp_readiness_registry.json", macro);
check(manifest.pinned_commit === "f7ffc821b0ade71dd38539e4044e25368dfb4dc1" && !manifest.newer_commit_detected, "Author commit pin failed.");
check(Object.values(manifest.files).every((value) => /^[a-f0-9]{64}$/.test(value)), "Reference checksums incomplete.");
check(manifest.licenses.data.name === "CC BY 4.0" && manifest.licenses.code.name === "BSD 3-Clause", "License audit failed.");
check(exclusions.exclusion_count === 3 && exclusions.records.every((row) => row.source_present), "Joint-event exclusions failed.");
check(pc1.status === "passed" && pc1.matched_row_count === 312 && pc1.maximum_absolute_difference_after_rounding === 0 && pc1.centering === false, "PC1 replication failed.");
check(poor.status === "passed" && poor.maximum_absolute_difference === 0 && poor.identity_maximum_difference === 0, "Poor-man replication failed.");
check(median.status === "passed" && median.maximum_absolute_difference_after_rounding === 0 && median.rng_used === false && median.identity_maximum_difference <= 1e-8, "Median replication failed.");
check(Math.abs(median.rotation_angle_radians - 0.7051099539973873) <= 1e-12, "Median rotation angle changed.");
check(monthly.status === "passed" && monthly.matched_row_count === 322 && monthly.no_event_month === 0, "Monthly replication failed.");
check(comparison.status === "passed" && Object.values(comparison.checks).every(Boolean), "Author comparison failed.");
check(cross.status === "passed" && cross.failed_row_count === 0, "Cross-language validation failed.");
check(event.identification_status === "identified_shock" && event.record_count === 312 && event.structural_component_count === 624, "Event shock publication failed.");
check(event.records.every((row) => Math.abs(row.monetary_policy_component + row.information_component - row.pc1) <= 1e-8), "MP+CBI identity failed.");
check(mp.identification_status === "identified_shock" && cbi.identification_status === "identified_shock" && mp.record_count === 322 && cbi.record_count === 322, "Monthly shocks were not activated.");
check(info.records.every((row) => row.information_effect_handling === "separated_under_jk_framework" && row.identified_shock_allowed), "Information-effect status failed.");
check(shocks.identified_shock_count === 2 && shocks.external_innovation_proxy_count === 3, "Shock counts failed.");
check(lp.method_state === "registry_only" && lp.shock_identification_ready_count === 2 && lp.estimator_ready_count === 0 && lp.causal_lp_ready_count === 0, "LP boundary failed.");
if (failures.length) { console.error(`Author-reference validation failed (${failures.length}/${tests}).`); failures.forEach((item) => console.error(`- ${item}`)); process.exit(1); }
console.log(`Author-reference validation passed: ${tests} tests; events=${event.record_count}; identified shocks=${shocks.identified_shock_count}; LP=${lp.method_state}.`);
