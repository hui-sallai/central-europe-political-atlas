import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';

for(const en of [true,false]) test(`Annual selection and separate dated reference · ${en?'en':'zh'}`,async({page})=>{
  const path=(en?'/en':'')+'/data/?compare_countries=poland,serbia&comparison_indicator=annual:fdi_inflow&comparison_mode=side_by_side&comparison_period=2025';
  await page.goto(path);
  const panel=page.locator('[data-national-comparison]');
  const selected=panel.locator('fieldset input:checked');
  await expect(selected).toHaveCount(2);
  await expect(panel.locator('[data-comparison-value]')).toHaveText(['—','—']);
  const reference=panel.locator('[data-annual-reference]');
  await reference.locator('summary').first().click();
  await expect(reference).toContainText('2015, 2016, 2022');
  const waiting=page.waitForEvent('download');
  await reference.getByRole('button',{name:en?'Download reference observations (CSV)':'下载参考观测（CSV）',exact:true}).click();
  const csv=await readFile((await (await waiting).path())!,'utf8');
  expect(csv).toContain('"vintage:annual:poland:fdi_inflow:2025","poland","fdi_inflow","2025","20734.5"');
  expect(csv).not.toContain('vintage:annual:serbia:fdi_inflow:2025');
  await expect(panel.locator('[data-comparison-value]')).toHaveText(['—','—']);
  const metric=panel.getByLabel(en?'Indicator':'指标',{exact:true});
  await metric.selectOption('annual:real_gdp_growth');
  for(const b of (await panel.locator('fieldset input:not(:checked)').all()).slice(0,3))await b.check();
  await expect(selected).toHaveCount(5);
  await page.reload();
  await expect(selected).toHaveCount(5);
  await expect(metric).toHaveValue('annual:real_gdp_growth');
  const d=page.waitForEvent('download');
  await panel.getByRole('button',{name:en?'Export research snapshot':'导出研究快照',exact:true}).click();
  const file=await (await d).path();
  const rows=JSON.parse(execFileSync('python3',['-c','import sys,zipfile,json,csv,io;z=zipfile.ZipFile(sys.argv[1]);print(json.dumps(list(csv.DictReader(io.StringIO(z.read("data.csv").decode("utf-8-sig"))))))',file!],{encoding:'utf8'}));
  const expected=(await (await page.request.get('/research-data/observations.json')).json());
  const actual=(expected.records??expected).find((r:{country_id:string;indicator_id:string;year:string})=>r.country_id==='poland'&&r.indicator_id==='real_gdp_growth'&&r.year==='2025');
  expect(Number(rows.find((r:{id:string})=>r.id===actual.observation_id).value)).toBe(actual.value);
  const frequency=panel.getByLabel(en?'Frequency':'观测频率',{exact:true});
  await frequency.selectOption('quarterly');
  await expect(metric).toHaveValue('');
  await expect(selected).toHaveCount(5);
  await metric.selectOption('sors:lfs_unemployment_quarterly');
  await expect(panel.locator('[data-common-periods]')).toContainText('—');
  await expect(reference).toHaveCount(0);
});

test('Official empty year and a change of source attribution stay inspectable',async({page})=>{
 await page.goto('/en/data/?compare_countries=slovakia,germany&comparison_indicator=annual:automotive_export_share&comparison_period=2015&comparison_mode=side_by_side');
 const panel=page.locator('[data-national-comparison]');
 await expect(panel.locator('fieldset input:checked')).toHaveCount(2);
 await panel.getByText('Historical coverage and exclusions',{exact:true}).click();
 const sk=panel.locator('[data-country-coverage="slovakia"]');
 await expect(sk).toContainText('Officially missing period: 2015');
 await expect(panel.locator('[data-comparison-value]').first()).toHaveText('—');
 await panel.getByLabel('Indicator',{exact:true}).selectOption('annual:gdp_current_eur');
 await panel.getByLabel('From period',{exact:true}).fill('2020');
 await panel.getByLabel('To period',{exact:true}).fill('2021');
 await panel.getByLabel('Visualization').selectOption('table');
 const details=panel.locator('[data-comparison-records]');
 const targets=details.locator('tbody tr').filter({hasText:'Germany'});
 await expect(targets).toHaveCount(2);
 await expect(targets.filter({hasText:'2020'})).toContainText('Eurostat nama_10_gdp');
 await expect(targets.filter({hasText:'2021'})).toContainText('Destatis');
});
