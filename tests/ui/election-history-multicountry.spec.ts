import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { activeNotebookRaw } from "./notebook-storage";

test("historical comparison restores dates, chamber events, browser navigation and the selected language",async({page})=>{
  await page.goto("/en/politics/?history_countries=hungary,romania,croatia,slovakia&history_from=2024-01-01&history_to=2024-12-31#historical-comparison");
  const panel=page.locator("[data-history-comparison]");
  const count=panel.locator("[data-history-count]");
  await expect(count).toContainText("Romania 1/2");
  await expect(count).toContainText("Slovakia 0/0");
  const croatia=panel.locator('[data-history-record="el-hr-sabor-2024-04-17"]');
  await expect(croatia).toContainText("61.48%");
  await expect(croatia).toContainText("Territorial constituencies I–X");
  const choice=panel.getByRole("combobox",{name:"Measure",exact:true});
  await choice.selectOption("chamber_seats");
  const senate=panel.locator('[data-history-record="el-ro-s-2024-12-01"]');
  await expect(senate.locator("strong")).toHaveText("136");
  await expect(senate).toContainText("Assigned seats · 134");
  await panel.getByText("Choose individual chamber elections",{exact:true}).click();
  const country=panel.locator('[data-history-events="romania"]');
  await country.locator("summary").click();
  await country.getByRole("checkbox",{name:"2024-12-01 · Camera Deputaților",exact:true}).uncheck();
  await expect(count).toContainText("Romania 1/1");
  await page.reload();
  await expect(count).toContainText("Romania 1/1");
  await page.goBack();
  await expect(count).toContainText("Romania 1/2");
  await page.goForward();
  await expect(count).toContainText("Romania 1/1");
  await page.locator('a[hreflang="zh-CN"]').click();
  await expect(panel.getByRole("combobox",{name:"比较指标",exact:true})).toHaveValue("chamber_seats");
  await expect(count).toContainText("罗马尼亚 1/1");
  await expect(page).toHaveURL(/#historical-comparison$/);
});

test("historical ballot comparison preserves sources and reopens from Notebook; invalid URLs fail closed",async({page})=>{
  await page.goto("/en/politics/?history_countries=hungary,croatia&history_events=el-hu-ogy-2018-04-08,el-hr-sabor-2024-04-17&history_measure=distribution#historical-comparison");
  const panel=page.locator("[data-history-comparison]");
  const croatia=panel.locator('[data-history-record="el-hr-sabor-2024-04-17"]');
  await croatia.getByRole("combobox").selectOption("hr-ie-11");
  const hungary=panel.locator('[data-history-record="el-hu-ogy-2018-04-08"]');
  await hungary.getByRole("combobox").selectOption("hu_nationality_list_vote");
  await hungary.getByText("Inspect distribution",{exact:true}).click();
  await expect(hungary).toContainText("Election-wide turnout");
  await expect(hungary).toContainText("Whole-chamber seat-share denominator");
  await expect(croatia.locator("a").first()).toHaveAttribute("href",/ballot=hr-ie-11/);
  await panel.getByRole("button",{name:"Save historical comparison",exact:true}).click();
  await expect.poll(()=>activeNotebookRaw(page)).toContain("admitted_parliamentary_election_history");
  const raw=JSON.parse(await activeNotebookRaw(page));
  const item=raw.items.find((i:{layer:string})=>i.layer==="admitted_parliamentary_election_history");
  expect(item.source_ids.length).toBeGreaterThan(0);
  const restored=new URL(item.url);
  expect(restored.searchParams.get("history_ballots")).toContain("hu_nationality_list_vote");
  const [file]=await Promise.all([page.waitForEvent("download"),panel.getByRole("button",{name:/Export selected evidence/}).click()]);
  const csv=await readFile((await file.path())!,"utf8");
  expect(csv).toContain("hr-ie-11");
  expect(csv).toContain("hu_nationality_list_vote");
  expect(csv).toContain("source_urls");
  expect(csv).not.toContain("hr-ie-12-");
  await page.goto("/en/notebook/");
  await page.goto(restored.pathname+restored.search+restored.hash);
  await expect(croatia.getByRole("combobox")).toHaveValue("hr-ie-11");
  await expect(hungary.getByRole("combobox")).toHaveValue("hu_nationality_list_vote");
  await panel.getByRole("combobox",{name:"Measure",exact:true}).selectOption("turnout");
  await expect(croatia.locator("a").first()).toHaveAttribute("href","/en/politics/croatia/?election=el-hr-sabor-2024-04-17");
  await expect(croatia).toContainText("Territorial constituencies I–X");
  await expect(hungary.locator("a").first()).toHaveAttribute("href","/en/politics/hungary/?election=el-hu-ogy-2018-04-08");
  await expect(hungary).toContainText("Election-wide electorate");
  await page.goto("/en/politics/?history_countries=hungary,slovakia&history_events=unregistered");
  await expect(panel).toContainText("unrecognized selection");
  await expect(panel.locator("[data-history-record]")).toHaveCount(0);
  await expect(panel.locator("[data-notebook-add]")).toHaveCount(0);
});
