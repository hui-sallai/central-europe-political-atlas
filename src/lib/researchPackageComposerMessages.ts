export const SHA256_PATTERN = /^[0-9a-f]{64}$/;

export function formatByteLength(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KiB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
}

/**
 * Deterministic local fingerprint matching the R1-C1 core's evidenceState()
 * so the composer drops stale handles immediately when an evidence item or
 * any referenced source record changes (including user-authored notes).
 */
export function evidenceFingerprint(projectId: string, notebook: ResearchNotebook, evidenceId: string): string | null {
  const item = notebook.items.find(entry => entry.id === evidenceId);
  if (!item) return null;
  const sources = notebook.sources.filter(source => item.source_ids.includes(source.id));
  return JSON.stringify([projectId, notebook.notebook_id, item, sources]);
}

export function normalizeExpectedDigest(raw: string): { ok: true; value: string | undefined } | { ok: false } {
  const trimmed = raw.trim().toLowerCase();
  if (!trimmed) return { ok: true, value: undefined };
  if (!SHA256_PATTERN.test(trimmed)) return { ok: false };
  return { ok: true, value: trimmed };
}

export function classifyComposerError(err: unknown): { code: string; detail: string } {
  if (err && typeof err === "object" && "code" in err && typeof (err as { code?: unknown }).code === "string") {
    const code = (err as { code: string }).code;
    const detail = err instanceof Error ? err.message : code;
    return { code, detail };
  }
  return { code: "unknown_error", detail: err instanceof Error ? err.message : "Unexpected error" };
}

